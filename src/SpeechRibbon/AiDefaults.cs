namespace SpeechRibbon;
internal static class AiDefaults {
    public const string Prompt = """
        Составь краткую и понятную сводку записи на русском языке по её транскрибации.
        
        Сначала передай суть записи в 2–3 предложениях. Затем перечисли основные мысли и важные детали, сохраняя смысл исходного текста.
        
        Если в записи есть явно принятые решения, конкретные задачи или оставшиеся без ответа вопросы, выдели их в отдельные разделы. Не добавляй разделы, для которых нет данных. Отличай принятые решения от предложений. Для задач укажи ответственного и срок, только если они названы; иначе отметь, что они не указаны.
        
        Опирайся только на транскрибацию. Не додумывай факты, имена, даты и намерения участников. Сохраняй важные числа, условия и отрицания. При необходимости указывай обозначения говорящих из текста, не угадывая их имена. Существенные неясности и противоречия отмечай, не разрешая их догадкой. Если текста недостаточно для сводки, кратко объясни это.
        
        Пиши без вступлений и повторов. Подбирай объём сводки по содержанию записи.
